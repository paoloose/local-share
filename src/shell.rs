use crate::app::App;
use leptos::prelude::*;
use leptos_meta::MetaTags;

/// The SSR document shell. Styles and hydration scripts are injected by
/// cargo-leptos' standard helpers.
pub fn shell(options: LeptosOptions) -> impl IntoView {
    view! {
        <!DOCTYPE html>
        <html lang="en">
            <head>
                <meta charset="utf-8"/>
                <meta name="viewport" content="width=device-width, initial-scale=1"/>
                <AutoReload options=options.clone()/>
                <HydrationScripts options/>
                <MetaTags/>
            </head>
            <body>
                <App/>
            </body>
        </html>
    }
}
